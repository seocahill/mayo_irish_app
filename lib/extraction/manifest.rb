# frozen_string_literal: true

require "date"
require "digest"
require "yaml"
require "open3"
require "time"

module Extraction
  # Keeps scans/MANIFEST.yml: one entry per source file with its hash, page
  # count and status, so new or changed files are noticed instead of ignored.
  #
  # Statuses: new, inventoried, scoped, extracting, done. The script sets
  # `new` (never seen, or the file's hash changed); a person or the scoper
  # step moves a file along from there, and the script preserves what they set.
  class Manifest
    SOURCE_EXTENSIONS = %w[.pdf .docx .jpg .jpeg .png].freeze
    STATUSES = %w[new inventoried scoped extracting done].freeze
    QUEUE_STATUSES = %w[pending proposed needs_scoping done skipped].freeze

    attr_reader :root

    def initialize(root: Dir.pwd)
      @root = root
    end

    def manifest_path = File.join(root, "scans", "MANIFEST.yml")
    def queue_path = File.join(root, "extraction_queue.yml")

    def previous
      return {} unless File.exist?(manifest_path)

      files = YAML.safe_load_file(manifest_path, permitted_classes: [ Date, Time ])&.fetch("files", nil) || []
      files.index_by { |f| f["path"] }
    end

    def source_files
      Dir.glob(File.join(root, "scans", "**", "*"))
         .select { |p| File.file?(p) && SOURCE_EXTENSIONS.include?(File.extname(p).downcase) }
         .map { |p| p.delete_prefix("#{root}/") }
         .sort
    end

    # Returns the entries as they should now be written.
    def build
      old = previous
      source_files.map do |path|
        sha = Digest::SHA256.file(File.join(root, path)).hexdigest
        prior = old[path]
        entry = {
          "path" => path,
          "sha256" => sha,
          "bytes" => File.size(File.join(root, path)),
          "pages" => page_count(path) || prior&.fetch("pages", nil),
          "status" => "new"
        }
        if prior && prior["sha256"] == sha
          entry["status"] = prior["status"] if STATUSES.include?(prior["status"])
          entry["covers"] = prior["covers"] if prior["covers"]
          entry["notes"] = prior["notes"] if prior["notes"]
        elsif prior
          entry["covers"] = prior["covers"] if prior["covers"]
          entry["prior_status"] = prior["status"]
          entry["notes"] = "Changed since last manifest (was #{prior['sha256'].to_s[0, 12]}); check coverage again."
        end
        entry.compact
      end
    end

    def write!
      entries = build
      header = <<~YAML
        # Generated by `bin/rails extraction:manifest`. Edit only `status`,
        # `covers` (page ranges, lesson and record ids) and `notes`; the rest is
        # rewritten from the files on disk. Statuses: #{STATUSES.join(' | ')}.
      YAML
      File.write(manifest_path, header + { "files" => entries }.to_yaml.sub(/\A---\n/, ""))
      entries
    end

    # Problems worth a person's attention. Empty means quiet.
    def problems(entries = build)
      found = []
      entries.each do |e|
        found << "#{e['path']}: new or changed, not yet inventoried" if e["status"] == "new"
      end

      queue = File.exist?(queue_path) ? (queue_units) : []
      queue.each do |u|
        found << "queue unit #{u['id']}: unknown status #{u['status'].inspect}" unless QUEUE_STATUSES.include?(u["status"])
        next unless u["status"] == "done"

        dir = u["scans"].to_s[%r{scans/[^/\s]+}]
        found << "queue unit #{u['id']}: done but scans #{dir.inspect} is not in scans/" if dir && entries.none? { |e| e["path"].start_with?("#{dir}/") }
      end

      done = entries.select { |e| e["status"] == "done" }
      done.each do |e|
        dir = File.dirname(e["path"])
        open_units = queue.select { |u| %w[pending proposed].include?(u["status"]) && u["scans"].to_s.include?(dir) }
        found << "#{e['path']}: marked done but queue has open units #{open_units.map { |u| u['id'] }.join(', ')}" if open_units.any?
      end
      found
    end

    # True when the nightly routine has nothing to do.
    def idle?
      return build.none? { |e| e["status"] == "new" } unless File.exist?(queue_path)

      units = queue_units
      units.none? { |u| %w[pending proposed needs_scoping].include?(u["status"]) } && build.none? { |e| e["status"] == "new" }
    end

    private

    def queue_units
      (YAML.safe_load_file(queue_path, permitted_classes: [ Date, Time ]) || {})["units"] || []
    end

    def page_count(path)
      return nil unless File.extname(path).casecmp(".pdf").zero?

      out, status = Open3.capture2("pdfinfo", File.join(root, path), err: File::NULL)
      return nil unless status.success?

      out[/^Pages:\s+(\d+)/, 1]&.to_i
    rescue Errno::ENOENT
      nil
    end
  end
end
